def pick(page, selector):
    page.click('#st-near-pick')
    page.click(selector)
    settle(page)
def matrix_coords_ok(url):
    m = re.search(r'/mapbox/[\w-]+/([^?]+)\?', url)
    return bool(m) and all(re.fullmatch(r'-?\d+(\.\d{1,2})?,-?\d+(\.\d{1,2})?', p) for p in m.group(1).split(';'))

