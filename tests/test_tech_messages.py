import sys, time, pathlib
from playwright.sync_api import sync_playwright
HERE = pathlib.Path(__file__).parent
TOOLBOX = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent / 'toolbox.js').read_text()
URL = (HERE / 'board_techs.html').as_uri()
fails = []
def check(c, w):
    print(('PASS ' if c else 'FAIL ') + w)
    if not c: fails.append(w)
def B(page, t): return page.locator('#st-toolbox button:visible', has_text=t).first
def T(page): return page.locator('#st-toolbox').inner_text()
def lit(page, id): return page.evaluate("id => getComputedStyle(document.querySelector('.technician[data-technician-id=\"' + id + '\"]')).outlineStyle", str(id)) == 'solid'
with sync_playwright() as p:
    b = p.chromium.launch(); page = b.new_page(viewport={'width': 1400, 'height': 900})
    errors = []; page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL + '#/DispatchBoard'); page.wait_for_selector('.technician')
    page.evaluate(TOOLBOX)
    B(page, 'Tech Messages').click()
    check('First, set up who can be messaged' in T(page), 'first-time setup still required')
    check(B(page, '🛡️ Set up').count() == 1, 'a 🛡️ Set up button shows until it is done')
    B(page, 'Pick on board').click()
    check('Who can be messaged' in T(page), 'Pick on board sends you to 🛡️ setup first')
    B(page, 'Save').click()
    check(B(page, '🛡️ Set up').count() == 0, '🛡️ Set up goes away once it is done')
    check(B(page, '👥 Choose techs').count() == 1 and B(page, 'Pick on board').count() == 1, 'main view keeps 👥 Choose techs and adds 🖱️ Pick on board')
    B(page, 'Pick on board').click()
    check(B(page, 'Picking: ON').count() == 1, 'picking turns on')
    page.click('#team-technician-1 .name')
    check(page.evaluate("() => window.opened.length") == 0, 'tech click captured while picking (menu not opened)')
    check('Tech One · Install HVAC' in T(page) and 'To: 1 tech' in T(page), 'tech added to the list')
    check(lit(page, 1), 'picked tech highlighted on the board')
    page.click('#team-technician-3 .name')
    check('Boss Man can\'t be messaged: their team (Leadership Team) is blocked.' in T(page) and 'To: 1 tech' in T(page), 'blocked tech not added, with the reason')
    page.click('#team-technician-2')
    check('To: 2 techs' in T(page), 'second tech added')
    page.click('#team-technician-1 .name')
    check('To: 1 tech' in T(page) and not lit(page, 1), 'clicking again takes a tech off')
    page.click('a.appointment[data-job-id="7001"]')
    check(page.evaluate("() => window.opened") == ['job7001'], 'job bubbles not captured by Tech Messages picking')
    page.evaluate("() => { window.opened = []; }")
    page.locator('#st-toolbox .tbx-body button:visible', has_text='✕').last.click()
    check('nobody picked yet' in T(page), '✕ in the list removes a tech')
    # 👥 Choose techs and the board list are the same selection
    B(page, 'Choose techs').click()
    page.locator('#st-toolbox label:visible', has_text='Tech One').locator('input').check()
    check(lit(page, 1), 'ticking in 👥 Choose techs highlights on the board')
    B(page, 'Done').click()
    check('Tech One · Install HVAC' in T(page), 'ticked tech shows in the main list')
    # Leaving hides highlights and turns picking off; coming back restores highlights
    page.locator('#st-toolbox [data-nav="menu"]').click()
    check(not lit(page, 1), 'highlights hidden after leaving')
    page.click('#team-technician-2 .name')
    check(page.evaluate("() => window.opened") == ['tech2'], 'tech names open normally after leaving')
    page.evaluate("() => { window.opened = []; }")
    B(page, 'Tech Messages').click()
    check(lit(page, 1) and B(page, 'Pick on board').count() == 1, 'highlight back on return, picking off')
    # Starting turns picking off
    B(page, 'Pick on board').click()
    B(page, 'Start').click()
    check('Check before sending' in T(page), 'start opens the confirm screen')
    B(page, 'Cancel').click()
    check(B(page, 'Pick on board').count() == 1, 'picking turned off when starting')
    page.evaluate("() => window.__stToolbox.close()")
    page.click('#team-technician-1 .name')
    check(page.evaluate("() => window.opened") == ['tech1'] and not lit(page, 1), 'after closing: no highlights, clicks normal')
    check(errors == [], 'no page errors: %s' % errors)
    b.close()
print('\n%d FAILED' % len(fails) if fails else '\nALL PASSED')
for f in fails: print(' - ' + f)
sys.exit(1 if fails else 0)
