fails = []
def check(cond, what):
    print(('PASS ' if cond else 'FAIL ') + what)
    if not cond: fails.append(what)

def B(page, text):
    return page.locator('#st-toolbox button:visible', has_text=text).first
def T(page):
    return page.locator('#st-toolbox').inner_text()
def ev(page, js, arg=None):
    return page.evaluate(js, arg) if arg is not None else page.evaluate(js)
def log(page):
    return ev(page, "() => Array.from(document.querySelectorAll('#st-toolbox pre')).map(p => p.textContent).join('\\n')")
def busy(page):
    return ev(page, "() => !!Array.from(document.querySelectorAll('#st-toolbox button')).find(b => b.offsetParent && /^Stop/.test(b.textContent))")
def wait_done(page, t=120):
    time.sleep(0.5); end = time.time() + t
    while time.time() < end:
        if not busy(page): return True
        time.sleep(0.25)
    return False
def wait_for(fn, secs=10):
    end = time.time() + secs
    while time.time() < end:
        v = fn()
        if v: return v
        time.sleep(0.1)
    return fn()
# Inside the board (its shadow root).
SR = "document.querySelector('[data-mfe-name=\"servicetitan-dispatch-center\"]').shadowRoot"
def card(appt):
    return '[data-cy="wdb-job-appt-card"][data-job-appointment-id="%s"]' % appt
def outline(page, appt):
    return ev(page, "(a) => { const b = " + SR + ".querySelector('[data-cy=\"wdb-job-appt-card\"][data-job-appointment-id=\"' + a + '\"]'); return b ? getComputedStyle(b).outlineStyle : 'not drawn'; }", str(appt))
def header_lit(page, tech):
    return ev(page, "(t) => { const h = " + SR + ".querySelector('[data-cy=\"ddb-technician-header-' + t + '\"]'); return h ? getComputedStyle(h).outlineStyle === 'solid' : null; }", str(tech))
def drawn(page, tech):
    return ev(page, "(t) => !!" + SR + ".querySelector('[data-cy=\"ddb-technician-header-' + t + '\"]')", str(tech))
def board_hash(page):
    return ev(page, "() => location.hash")
def add_typed(page, nums):
    page.fill('#st-toolbox input:visible[placeholder^="Or type job"]', nums)
    page.locator('#st-toolbox button:visible', has_text='Add').filter(has_not_text='All').filter(has_not_text='note').first.click()
def to_board(page):
    ev(page, "() => { location.hash = '#/DispatchBoard'; }")
    page.wait_for_selector('[data-cy^="ddb-technician-header-"]')
def menu(page):
    if B(page, '← Menu').count(): B(page, '← Menu').click()
def bar(page):
    return ev(page, "() => { const t = document.getElementById('st-toolbox').innerText; return t.split('\\n').filter(l => /^•/.test(l.trim())).join(' | '); }")
def iso(d):
    return d.strftime('%Y-%m-%dT00:00:00')

