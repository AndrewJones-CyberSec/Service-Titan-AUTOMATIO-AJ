import sys, time, pathlib
from playwright.sync_api import sync_playwright
HERE = pathlib.Path(__file__).parent
TOOLBOX = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent / 'toolbox.js').read_text()
URL = (HERE / 'board.html').as_uri()
fails = []
def check(c, w):
    print(('PASS ' if c else 'FAIL ') + w)
    if not c: fails.append(w)
def B(page, t): return page.locator('#st-toolbox button:visible', has_text=t).first
def T(page): return page.locator('#st-toolbox').inner_text()
def log(page): return page.evaluate("() => Array.from(document.querySelectorAll('#st-toolbox pre')).filter(p => p.offsetParent).map(p => p.textContent).join('\\n')")
def busy(page): return page.evaluate("() => !!Array.from(document.querySelectorAll('#st-toolbox button')).find(b => b.offsetParent && /^Stop/.test(b.textContent))")
def wait_done(page, t=120):
    time.sleep(0.5); end = time.time() + t
    while time.time() < end:
        if not busy(page): return True
        time.sleep(0.3)
    return False
with sync_playwright() as p:
    b = p.chromium.launch(); page = b.new_page(viewport={'width': 1400, 'height': 900})
    errors = []; page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL + '#/DispatchBoard'); page.wait_for_selector('a.appointment')
    page.evaluate(TOOLBOX)
    B(page, 'Job Notifications').click()
    check(page.locator('#st-notify-tech').is_visible() and 'Tech One' in page.evaluate("() => document.getElementById('st-notify-tech').textContent"), 'tech picker still there by default')
    page.locator('#st-toolbox label:visible', has_text='Jobs I pick').locator('input').check()
    check(not page.locator('#st-notify-tech').is_visible() and '0 jobs picked' in T(page), 'switches to picked jobs')
    check(B(page, 'Check jobs').is_disabled(), 'check disabled with nothing picked')
    B(page, 'Pick on board').click()
    page.click('a.appointment[data-job-id="111111"]')
    page.click('.job-list tr.qa-job-901003 td')
    check(page.evaluate("() => window.opened.length") == 0, 'clicks captured while picking')
    B(page, '+ All in the list').click()
    check('3 jobs picked' in T(page) and 'Added 1 job from the Hold list' in T(page), 'whole list tab added (no duplicates)')
    page.fill('#st-toolbox input:visible[placeholder^="Or type job"]', '222222')
    page.locator('#st-toolbox button:visible', has_text='Add').filter(has_not_text='All').filter(has_not_text='note').first.click()
    check('4 jobs picked' in T(page) and 'Tray Cust 901004' in T(page), 'typed job added; list labels show customer')
    page.evaluate("() => { window.NOTIF = { '222222': false }; window.indexOpened = []; }")
    t0 = time.time()
    B(page, 'Check jobs').click()
    check(wait_done(page), 'check run finishes')
    secs = time.time() - t0
    check(page.evaluate("() => (window.indexOpened || []).length") == 0 and secs < 5, 'check reads job data only: no job pages opened, %.1fs' % secs)
    lg = log(page); print(lg)
    check('Picked jobs (4) (checking only' in lg and lg.count('ON (left alone)') == 3 and '222222: already off' in lg, 'check reports each picked job')
    check(page.evaluate("() => JSON.stringify(window.NOTIF)") == '{"222222":false}', 'check changed nothing')
    check('4 jobs picked' in T(page), 'check keeps the list')
    B(page, 'Turn off notifications').click()
    check('Turn OFF notifications on 4 picked jobs?' in T(page), 'confirm counts picked jobs')
    page.evaluate("() => { window.indexOpened = []; }")
    B(page, 'Yes, turn them off').click()
    check(wait_done(page), 'turn-off run finishes')
    lg = log(page); print(lg)
    opened = page.evaluate("() => window.indexOpened")
    check('222222' not in opened and len(opened) == 3, 'only jobs that were on get opened: %s' % opened)
    check(page.evaluate("() => Object.values(window.NOTIF).every(v => !v)") and lg.count('turned off') == 3, 'notifications turned off on picked jobs')
    check('0 jobs picked' in T(page), 'done jobs come off the list')
    check(page.evaluate("() => location.hash").startswith('#/DispatchBoard'), 'back on the board')

    # Turn notifications back ON for picked jobs
    def add_typed(nums):
        page.fill('#st-toolbox input:visible[placeholder^="Or type job"]', nums)
        page.locator('#st-toolbox button:visible', has_text='Add').filter(has_not_text='All').filter(has_not_text='note').first.click()
    page.evaluate("() => { window.NOTIF = { '111111': false, '222222': false, '901003': true }; window.indexOpened = []; }")
    add_typed('111111 222222 901003')
    check('3 jobs picked' in T(page), 'three jobs picked for turning on')
    check(not B(page, 'Turn on notifications').is_disabled(), 'turn-on button enabled with jobs picked')
    B(page, 'Turn on notifications').click()
    t = T(page)
    check('Turn ON notifications on 3 picked jobs?' in t, 'turn-on confirm counts picked jobs')
    check("automatic job notifications again" in t, 'turn-on confirm says customers will be notified again')
    check(B(page, 'Yes, turn them on').count() == 1 and B(page, 'Yes, turn them off').count() == 0, 'confirm button says turn them on')
    check(page.evaluate("() => JSON.stringify(window.NOTIF)") == '{"111111":false,"222222":false,"901003":true}', 'nothing changed before confirming')
    B(page, 'Yes, turn them on').click()
    check(wait_done(page), 'turn-on run finishes')
    lg = log(page); print(lg)
    opened = page.evaluate("() => window.indexOpened")
    check(sorted(opened) == ['111111', '222222'], 'only jobs that were off get opened: %s' % opened)
    check(page.evaluate("() => Object.values(window.NOTIF).every(v => v === true)"), 'notifications turned on on picked jobs')
    check(lg.count('turned on') == 2 and '901003: already on' in lg and 'turned off' not in lg, 'log shows turned on / already on')
    check('Picked jobs (3) (turning notifications ON)' in lg, 'log says it was turning notifications ON')
    check('0 jobs picked' in T(page), 'turned-on jobs come off the list')
    check(page.evaluate("() => location.hash").startswith('#/DispatchBoard'), 'back on the board after turning on')

    # Turning off still asks the off question after a turn-on (the confirm box resets)
    add_typed('111111')
    B(page, 'Turn on notifications').click()
    B(page, 'Turn off notifications').click()
    t = T(page)
    check('Turn OFF notifications on 1 picked job?' in t and 'again' not in t.split('Turn OFF')[1].split('Cancel')[0] and B(page, 'Yes, turn them off').count() == 1, 'confirm switches back to the off question')
    B(page, 'Cancel').click()
    check(page.evaluate("() => window.NOTIF['111111']") is True, 'cancel changed nothing')

    # A switch that won't stay on is reported, retried once, and the job stays on the list
    page.evaluate("() => { window.NOTIF = { '111111': false }; window.NOTIF_STUCK = { '111111': true }; window.indexOpened = []; }")
    B(page, 'Turn on notifications').click()
    B(page, 'Yes, turn them on').click()
    check(wait_done(page), 'stuck turn-on run finishes')
    lg = log(page); print(lg)
    check(('FLIPPED BACK OFF' in lg or 'FAILED, still off' in lg) and 'Still a problem after retry: 111111' in lg, 'switch that snaps back is reported and retried')
    check(page.evaluate("() => window.NOTIF['111111']") is False and '1 job picked' in T(page), 'not saved, and the job stays on the list')
    page.evaluate("() => { window.NOTIF_STUCK = {}; }")
    B(page, 'Clear').click()

    # Tech mode still works
    page.locator('#st-toolbox label:visible', has_text="A tech's jobs").locator('input').check()
    check(page.locator('#st-notify-tech').is_visible(), 'back to the tech picker')
    page.evaluate("() => { window.NOTIF = {}; }")
    B(page, 'Check jobs').click()
    check(wait_done(page, 150), 'tech check run finishes')
    lg = log(page); print(lg)
    check(' - Tech One (checking only' in lg and lg.count('ON (left alone)') == 8, 'tech mode checks all 8 of the tech\'s jobs')
    check('Tech One  (8 jobs)' in page.evaluate("() => document.getElementById('st-notify-tech').textContent"), 'tech list shows job counts')
    B(page, 'Turn on notifications').click()
    check('Turn ON notifications on 8 jobs for Tech One on' in T(page), "turn-on confirm names the tech and the day")
    B(page, 'Cancel').click()
    # Job data unreadable: falls back to opening each job, same results
    page.evaluate("() => { window.API_DOWN = true; window.indexOpened = []; window.NOTIF = { '444444': false }; }")
    B(page, 'Check jobs').click()
    check(wait_done(page, 150), 'check with job data down finishes')
    lg = log(page); print(lg)
    check(lg.count('ON (left alone)') == 7 and '444444: already off' in lg and len(page.evaluate("() => window.indexOpened")) == 8, 'fallback opens each job and gives the same answers')
    page.evaluate("() => { window.API_DOWN = false; window.NOTIF = {}; }")
    # A login that can't open job records: stops right away and says why (no pages, no "ServiceTitan changed")
    page.evaluate("() => { window.JOB_NO_PERMISSION = true; window.indexOpened = []; window.NOTIF = { '111111': false }; }")
    B(page, 'Turn on notifications').click()
    B(page, 'Yes, turn them on').click()
    check(wait_done(page, 60), 'no-permission run ends')
    lg = log(page); print(lg)
    t = T(page)
    check("doesn't have permission to open job records" in lg and 'Nothing was changed' in t, 'says the login lacks permission')
    check('signed you out' not in t and 'COULD NOT FIND SWITCH' not in lg and "can't find the Job Notifications switch" not in t, 'not blamed on sign-out or a ServiceTitan change')
    check(len(page.evaluate("() => window.indexOpened")) == 0 and page.evaluate("() => window.NOTIF['111111']") is False, 'no job pages opened, nothing changed')
    page.evaluate("() => { window.JOB_NO_PERMISSION = false; window.NOTIF = {}; }")
    # Picking far down a long list must not jump the page (and still picks the job)
    B(page, 'Clear').click() if B(page, 'Clear').count() else None
    page.locator('#st-toolbox label:visible', has_text='Jobs I pick').locator('input').check()
    B(page, 'Pick on board').click()
    page.evaluate("() => document.querySelector('.job-list tr.qa-job-950055').scrollIntoView({ block: 'center' })")
    y0 = page.evaluate("() => window.scrollY")
    for j in ['950054', '950055', '950056']:
        page.click('.job-list tr.qa-job-%s td' % j)
    time.sleep(0.4)
    y1 = page.evaluate("() => window.scrollY")
    check(abs(y1 - y0) < 2 and '3 jobs picked' in T(page), 'no jump when picking deep in the list (scroll %d -> %d)' % (y0, y1))
    check(page.evaluate("() => document.activeElement === document.querySelector('.job-list table')") is False, 'the list did not take focus')
    B(page, 'Picking: ON').click()
    page.evaluate("() => { window.opened = []; }")
    page.click('.job-list tr.qa-job-950057 td')
    time.sleep(0.2)
    y2 = page.evaluate("() => window.scrollY")
    check(y2 < y1 - 200, 'without picking, the fake list jumps like the real one (test is valid): %d -> %d' % (y1, y2))
    page.evaluate("() => { window.opened = []; window.scrollTo(0, 0); }")
    # Timeline: pressing a job while picking can't start a drag
    B(page, 'Pick on board').click()
    page.evaluate("() => { window.pressed = 0; document.querySelector('a.appointment').parentElement.addEventListener('mousedown', () => window.pressed++); }")
    page.click('a.appointment[data-job-id="333333"]')
    check(page.evaluate("() => window.pressed") == 0 and '4 jobs picked' in T(page), 'timeline press swallowed while picking (no drag start)')
    B(page, 'Picking: ON').click()
    page.click('a.appointment[data-job-id="333333"]')
    check(page.evaluate("() => window.pressed") == 1, 'timeline press works normally when not picking')
    page.evaluate("() => { window.opened = []; }")

    # Highlights only show while the tool is open
    lit = lambda: page.evaluate("() => ({ bubble: getComputedStyle(document.querySelector('a.appointment[data-job-id=\"333333\"]')).outlineStyle, row: getComputedStyle(document.querySelector('.job-list tr.qa-job-950055 > td')).backgroundColor })")
    l0 = lit()
    check(l0['bubble'] == 'solid' and l0['row'] not in ('rgba(0, 0, 0, 0)', 'transparent'), 'picked jobs highlighted while Job Notifications is open')
    B(page, '← Menu').click()
    l1 = lit()
    check(l1['bubble'] != 'solid' and l1['row'] in ('rgba(0, 0, 0, 0)', 'transparent'), 'highlights gone after leaving: %s' % l1)
    B(page, 'Customer Texts').click()
    check(lit()['bubble'] != 'solid', 'no Job Notifications highlights inside Customer Texts')
    page.evaluate("() => { const b = Array.from(document.querySelectorAll('#st-toolbox button')).find(b => /Menu/.test(b.textContent) && b.offsetParent); if (b) b.click(); }")
    B(page, 'Job Notifications').click()
    check(lit()['bubble'] == 'solid' and '4 jobs picked' in T(page), 'highlights and list come back on return')
    page.locator('#st-toolbox label:visible', has_text="A tech's jobs").locator('input').check()
    check(lit()['bubble'] != 'solid', "no highlights in A tech's jobs mode")

    # Leaving the tool turns picking off
    page.locator('#st-toolbox label:visible', has_text='Jobs I pick').locator('input').check()
    B(page, 'Pick on board').click()
    B(page, '← Menu').click()
    page.click('a.appointment[data-job-id="111111"]')
    check(page.evaluate("() => window.opened.length") == 1, 'picking turns off when leaving the tool')
    page.evaluate("() => window.__stToolbox.close()")
    check(errors == [], 'no page errors: %s' % errors)
    b.close()
print('\n%d FAILED' % len(fails) if fails else '\nALL PASSED')
for f in fails: print(' - ' + f)
sys.exit(1 if fails else 0)
